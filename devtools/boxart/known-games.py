#!/usr/bin/env python3
"""
Known games for box art (Joey 2026-11-07): turns the covers a Joey64 library found on ScreenScraper
into lines of app/src/main/assets/boxart/fixes.tsv, so those games' covers are fetched by ID with no
lookup (BoxArtFixes.kt).

Usage: python devtools/boxart/known-games.py <library.db> [more library.db ...]
  library.db: a copy of the app's databases/library.db (with its -wal next to it, or checkpointed),
  e.g. from a device that looked up the 1,220-game test set.

Hand-checked lines (above the "# Generated" marker) are kept as they are and win: an MD5 they list is
not generated again. Games with no cover ("none") are left out, so a later lookup can still find one.
"""
import os
import re
import sqlite3
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
FIXES = os.path.join(HERE, '..', '..', 'app', 'src', 'main', 'assets', 'boxart', 'fixes.tsv')
MARKER = '# Generated by devtools/boxart/known-games.py from looked-up libraries; edit the lines above instead.'
COVER = re.compile(r'^screenscraper:(\d+):([a-z]{2,3})$')
COUNTRY = re.compile(r'\((Germany|France|Spain|Italy|Netherlands|Australia|Brazil|Korea|China)\b')


def main(dbs):
    text = open(FIXES, encoding='utf-8').read()
    hand = text.split(MARKER)[0].rstrip('\n') + '\n'
    listed = {l.split('\t')[0].lower() for l in hand.splitlines() if l and not l.startswith('#')}
    found = {}
    for path in dbs:
        c = sqlite3.connect(path)
        # 64DD disks (no header key: no header CRCs) are left out: their ScreenScraper games are system 122, which the
        # direct cover fetch (mediaJeu with systemeid 14) answers NOMEDIA for; their MD5 lookup through 14 finds them.
        rows = c.execute("SELECT g.md5, g.title, a.cover FROM games g JOIN box_art a ON a.game_id = g.id "
                         "WHERE a.kind = 'libretro' AND g.header_key IS NOT NULL")
        for md5, title, cover in rows:
            m = COVER.match(cover or '')
            if m and md5 not in listed:
                # A European country's release looked up before 2026-11-07 got the US cover: no region for it, so the
                # app looks the game up by ID and picks the region itself (BoxArtFixes: a line without a region).
                region = '' if COUNTRY.search(title or '') else m.group(2)
                found[md5] = (m.group(1), region, title)
    lines = [f'{md5}\t{gid}\t{region}\t{title}' for md5, (gid, region, title) in sorted(found.items(), key=lambda kv: kv[1][2].lower())]
    with open(FIXES, 'w', encoding='utf-8', newline='\n') as f:
        f.write(hand + MARKER + '\n' + ''.join(l + '\n' for l in lines))
    print(f'{len(lines)} known games generated, {len(listed)} hand-checked lines kept')


if __name__ == '__main__':
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    main(sys.argv[1:])
