#!/bin/sh
# Settings › Video's present pass shaders (app/src/main/cpp/shaders/): compiles post_*.comp (Vulkan)
# to SPIR-V with the NDK's glslc into shaders/post_spv.h, and flattens post_gl.frag (GLES, one per
# pass, glslc -E) into shaders/post_gl.h. Both are committed, so the app builds without glslc.
# Run after changing a shader: sh devtools/build-shaders.sh
set -e
cd "$(dirname "$0")/.."
NDK="${ANDROID_NDK_HOME:-$LOCALAPPDATA/Android/Sdk/ndk/27.3.13750724}"
GLSLC="$NDK/shader-tools/windows-x86_64/glslc.exe"
[ -x "$GLSLC" ] || GLSLC="$NDK/shader-tools/linux-x86_64/glslc"
S=app/src/main/cpp/shaders
FFX=app/src/main/cpp/third_party/ffx
TMP=$(mktemp -d)
compile() { # name ffx-dir
    "$GLSLC" --target-env=vulkan1.1 -O -I "$S" -I "$FFX/$2" -o "$TMP/$1.spv" "$S/$1.comp"
}
compile post_plain cas
compile post_cas cas
compile post_easu fsr1
compile post_rcas fsr1
compile post_look cas
OUT=$S/post_spv.h
{
    echo "// Generated by devtools/build-shaders.sh from shaders/post_*.comp. Do not edit."
    echo "#pragma once"
    echo "#include <cstdint>"
    for n in post_plain post_cas post_easu post_rcas post_look; do
        echo "static const uint32_t k_${n}_spv[] = {"
        od -An -v -tx4 -w16 "$TMP/$n.spv" | sed 's/ \([0-9a-f]\{8\}\)/0x\1,/g; s/^/   /'
        echo "};"
    done
} > "$OUT"
# GLES: preprocessed source per pass (includes expanded; #line and the include extension dropped,
# since GLES compilers take neither).
GL=$S/post_gl.h
{
    echo "// Generated by devtools/build-shaders.sh from shaders/post_gl.frag. Do not edit."
    echo "#pragma once"
    for pass in 0:cas 1:cas 2:fsr1 3:fsr1; do
        n=${pass%%:*}; d=${pass#*:}
        "$GLSLC" -E -DPASS=$n -I "$S" -I "$FFX/$d" -fshader-stage=frag "$S/post_gl.frag" -o "$TMP/gl$n.frag"
        echo "static const char k_post_gl${n}_frag[] = R\"GLSL("
        # GLSL ES has no implicit int -> uint: AMD's setup functions (unused on the GPU, but compiled)
        # assign 0 to uints. The vendored headers stay as they are.
        grep -v '^#line\|GL_GOOGLE_include_directive\|^[[:space:]]*$' "$TMP/gl$n.frag" | sed 's/\]= 0;/]= 0u;/g' > "$TMP/gl$n.es"
        # Checked as GLSL ES here (glslc's OpenGL target), so a driver doesn't find it first.
        "$GLSLC" --target-env=opengl -fauto-map-locations -fauto-bind-uniforms -fshader-stage=frag -c "$TMP/gl$n.es" -o "$TMP/gl$n.spv" >&2
        cat "$TMP/gl$n.es"
        echo ")GLSL\";"
    done
} > "$GL"
# The Picture pass (look.glsl) on GLES: one program.
LG=$S/look_gl.h
{
    echo "// Generated by devtools/build-shaders.sh from shaders/look_gl.frag. Do not edit."
    echo "#pragma once"
    "$GLSLC" -E -I "$S" -fshader-stage=frag "$S/look_gl.frag" -o "$TMP/look.frag"
    echo "static const char k_look_gl_frag[] = R\"GLSL("
    grep -v '^#line\|GL_GOOGLE_include_directive\|^[[:space:]]*$' "$TMP/look.frag" > "$TMP/look.es"
    "$GLSLC" --target-env=opengl -fauto-map-locations -fauto-bind-uniforms -fshader-stage=frag -c "$TMP/look.es" -o "$TMP/look.spv" >&2
    cat "$TMP/look.es"
    echo ")GLSL\";"
} > "$LG"
rm -rf "$TMP"
echo "wrote $OUT, $GL and $LG"
